"""Normalized trigger event schema emitted by entry and exit signal generators."""
from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
import time
from typing import Any, Dict, Optional


from botcore import safe_pos_float
from providers.base import normalize_side


class TriggerAction(str, Enum):
    ENTRY = "ENTRY"
    EXIT = "EXIT"
    NEUTRAL = "NEUTRAL"

    def __str__(self) -> str:
        return str(self.value)


class TriggerSide(str, Enum):
    BUY = "BUY"
    SELL = "SELL"
    HOLD = "HOLD"

    def __str__(self) -> str:
        return str(self.value)


@dataclass(frozen=True)
class TriggerEvent:
    """Actionable event generated by an entry/exit trigger before passing guards."""

    action: TriggerAction
    side: TriggerSide
    source: str
    symbol: str
    price: float
    strength: float
    ts: float = field(default_factory=time.time)
    velocity: Optional[float] = None
    confidence: Optional[float] = None
    reason: str = ""
    metadata: Dict[str, Any] = field(default_factory=dict)

    def is_executable(self) -> bool:
        """Return True if this event requests an actual order (BUY or SELL)."""
        px = safe_pos_float(self.price, default=None)
        if px is None:
            return False
        side_norm = (
            self.side.value
            if isinstance(self.side, TriggerSide)
            else normalize_side(self.side)
        )
        action_norm = (
            self.action.value
            if isinstance(self.action, TriggerAction)
            else ("" if isinstance(self.action, bool) or self.action is None else str(self.action).strip().upper())
        )
        return (
            side_norm in ("BUY", "SELL")
            and action_norm in ("ENTRY", "EXIT")
        )
