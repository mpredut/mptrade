def _detect_venue(report: dict, cli_venue: str | None = None) -> str:
    for raw in (
        cli_venue if not isinstance(cli_venue, bool) else None,
        report.get("venue") if isinstance(report, dict) and not isinstance(report.get("venue"), bool) else None,
    ):
        if raw is not None:
            v_str = str(getattr(raw, "name", raw) or "").strip().lower()
            if v_str:
                norm = normalize_venue_name(v_str) or v_str
                return "trading212" if norm == "t212" else norm
    purpose = str((report.get("purpose") if isinstance(report, dict) else None) or "").lower()
    if "binance" in purpose:
        return "binance"
    if "hyperliquid" in purpose:
        return "hyperliquid"
    if "trading212" in purpose or "trading 212" in purpose or "t212" in purpose:
        return "trading212"
    runtime = report.get("runtime") if isinstance(report, dict) else None
    if not isinstance(runtime, dict):
        runtime = {}
    if "profile" in runtime or str(runtime.get("ticker") or "").endswith("_EQ"):
        return "trading212"
    return "kraken"


def _load_report(path: Path) -> dict:
    report = read_json_file(path)
    if not isinstance(report, dict):
        raise ValueError("an incompatible or empty baseline report")
    intervals = report.get("intervals")
    has_intervals = isinstance(intervals, dict) and len(intervals) > 0
    has_single_dataset = isinstance(report.get("dataset"), dict) and (
        isinstance(report.get("windows"), dict) or isinstance(report.get("window_sizes"), dict)
    )
    if report.get("schema_version") != 1 or (not has_intervals and not has_single_dataset):
        raise ValueError("an incompatible or empty baseline report")
    return report


def _load_datasets(report: dict, baseline_dir: Path | None = None) -> dict[int, tuple[list[dict], dict, int]]:
    datasets = {}
    wf_cfg = report.get("walk_forward") if isinstance(report.get("walk_forward"), dict) else {}
    warmup_bars = safe_nonneg_int(wf_cfg.get("signal_warmup_bars"), default=0)

    def _resolve_frozen_file(raw_path: str | Path) -> Path:
        p = Path(raw_path).expanduser()
        if p.exists():
            return p
        if baseline_dir:
            if (baseline_dir / p.name).exists():
                return baseline_dir / p.name
            if (baseline_dir / "datasets" / p.name).exists():
                return baseline_dir / "datasets" / p.name
        if (ROOT / p).exists():
            return ROOT / p
        return p

    def _load_and_verify_frozen(raw_path: str | Path, expected_hash: object, interval: int) -> list[dict]:
        path = _resolve_frozen_file(raw_path)
        records = load_frozen_dataset(path)
        actual_hash = dataset_sha256(records)
        if actual_hash != expected_hash:
            raise ValueError(
                f"a different dataset hash for {interval}m: {actual_hash} != {expected_hash}"
            )
        return records

    if isinstance(report.get("intervals"), dict) and report["intervals"]:
        for interval_text, section in report["intervals"].items():
            interval = parse_interval_minutes(interval_text)
            if not isinstance(section, dict) or not isinstance(section.get("dataset"), dict):
                raise ValueError(f"missing dataset metadata for {interval}m")
            records = _load_and_verify_frozen(
                section["dataset"]["frozen_file"],
                section["dataset"]["sha256"],
                interval,
            )
            raw_ws = section.get("window_sizes") or section.get("windows")
            window_sizes = raw_ws if isinstance(raw_ws, dict) else {}
            warmup = safe_nonneg_int(window_sizes.get("signal_warmup_bars"), default=warmup_bars)
            datasets[interval] = (records, window_sizes, warmup)
    elif isinstance(report.get("dataset"), dict) and (
        isinstance(report.get("windows"), dict) or isinstance(report.get("window_sizes"), dict)
    ):
        runtime_meta = report.get("runtime") if isinstance(report.get("runtime"), dict) else {}
        dataset_meta = report["dataset"]
        exec_meta = report.get("execution_model") if isinstance(report.get("execution_model"), dict) else {}
        interval_raw = (
            runtime_meta.get("interval_minutes")
            or runtime_meta.get("interval")
        )
        if interval_raw is not None:
            interval = parse_interval_minutes(interval_raw)
        elif safe_pos_float(dataset_meta.get("median_step_seconds"), default=0.0) > 0:
            step_min = int(round(safe_pos_float(dataset_meta["median_step_seconds"], default=60.0) / 60.0))
            interval = 1440 if step_min >= 1440 else max(1, step_min)
        elif exec_meta.get("calendar_periods_per_year") == 252.0:
            interval = 1440
        else:
            interval = 240

        frozen_spec = dataset_meta.get("frozen_file")
        if not frozen_spec:
            source = str(dataset_meta.get("source", ""))
            if "frozen to " in source:
                frozen_spec = source.split("frozen to ", 1)[1].strip()
            elif "frozen file: " in source:
                frozen_spec = source.split("frozen file: ", 1)[1].strip()
        if not frozen_spec:
            raise ValueError(f"could not determine frozen dataset file path for {interval}m")
        records = _load_and_verify_frozen(frozen_spec, dataset_meta["sha256"], interval)
        raw_ws = report.get("windows") or report.get("window_sizes")
        window_sizes = raw_ws if isinstance(raw_ws, dict) else {}
        warmup = safe_nonneg_int(window_sizes.get("signal_warmup_bars"), default=warmup_bars)
        datasets[interval] = (records, window_sizes, warmup)
    return datasets


