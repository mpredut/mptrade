def _detect_venue(report: dict, cli_venue: str | None = None) -> str:
    if cli_venue:
        return cli_venue.strip().lower()
    if "venue" in report:
        return str(report["venue"]).strip().lower()
    purpose = report.get("purpose", "").lower()
    if "binance" in purpose:
        return "binance"
    if "hyperliquid" in purpose:
        return "hyperliquid"
    if "trading212" in purpose or "trading 212" in purpose or "t212" in purpose:
        return "trading212"
    runtime = report.get("runtime", {})
    if "profile" in runtime or str(runtime.get("ticker", "")).endswith("_EQ"):
        return "trading212"
    return "kraken"


def _load_report(path: Path) -> dict:
    with path.open("r", encoding="utf-8") as handle:
        report = json.load(handle)
    has_intervals = report.get("intervals") is not None and len(report.get("intervals", {})) > 0
    has_single_dataset = report.get("dataset") is not None and (
        report.get("windows") is not None or report.get("window_sizes") is not None
    )
    if report.get("schema_version") != 1 or (not has_intervals and not has_single_dataset):
        raise ValueError("an incompatible or empty baseline report")
    return report


def _load_datasets(report: dict, baseline_dir: Path | None = None) -> dict[int, tuple[list[dict], dict, int]]:
    datasets = {}
    warmup_bars = int(report.get("walk_forward", {}).get("signal_warmup_bars", 0))

    def _resolve_frozen_file(raw_path: str | Path) -> Path:
        p = Path(raw_path).expanduser()
        if p.exists():
            return p
        if baseline_dir:
            if (baseline_dir / p.name).exists():
                return baseline_dir / p.name
            if (baseline_dir / "datasets" / p.name).exists():
                return baseline_dir / "datasets" / p.name
        if (ROOT / p).exists():
            return ROOT / p
        return p

    if "intervals" in report:
        for interval_text, section in report["intervals"].items():
            interval = int(interval_text)
            path = _resolve_frozen_file(section["dataset"]["frozen_file"])
            records = load_frozen_dataset(path)
            actual_hash = dataset_sha256(records)
            expected_hash = section["dataset"]["sha256"]
            if actual_hash != expected_hash:
                raise ValueError(
                    f"a different dataset hash for {interval}m: {actual_hash} != {expected_hash}"
                )
            window_sizes = section.get("window_sizes") or section.get("windows")
            warmup = int(window_sizes.get("signal_warmup_bars", warmup_bars))
            datasets[interval] = (records, window_sizes, warmup)
    elif "dataset" in report and ("windows" in report or "window_sizes" in report):
        interval_raw = (
            report.get("runtime", {}).get("interval_minutes")
            or report.get("runtime", {}).get("interval")
        )
        if interval_raw is not None:
            try:
                interval = int(interval_raw)
            except ValueError:
                from binance_api.market_data import parse_interval_minutes
                interval = parse_interval_minutes(str(interval_raw))
        elif report.get("dataset", {}).get("median_step_seconds"):
            step_min = int(round(float(report["dataset"]["median_step_seconds"]) / 60.0))
            interval = 1440 if step_min >= 1440 else max(1, step_min)
        elif report.get("execution_model", {}).get("calendar_periods_per_year") == 252.0:
            interval = 1440
        else:
            interval = 240

        frozen_spec = report["dataset"].get("frozen_file")
        if not frozen_spec:
            source = str(report["dataset"].get("source", ""))
            if "frozen to " in source:
                frozen_spec = source.split("frozen to ", 1)[1].strip()
            elif "frozen file: " in source:
                frozen_spec = source.split("frozen file: ", 1)[1].strip()
        if not frozen_spec:
            raise ValueError(f"could not determine frozen dataset file path for {interval}m")
        path = _resolve_frozen_file(frozen_spec)
        records = load_frozen_dataset(path)
        actual_hash = dataset_sha256(records)
        expected_hash = report["dataset"]["sha256"]
        if actual_hash != expected_hash:
            raise ValueError(
                f"a different dataset hash for {interval}m: {actual_hash} != {expected_hash}"
            )
        window_sizes = report.get("windows") or report.get("window_sizes")
        warmup = int(window_sizes.get("signal_warmup_bars", warmup_bars))
        datasets[interval] = (records, window_sizes, warmup)
    return datasets


def _load_hl_replay():
    import importlib.util
    hl_dir = ROOT / "hyperliquid"
    spec = importlib.util.spec_from_file_location("hl_wf_replay", str(hl_dir / "replay.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _load_t212_replay():
    import importlib.util
    t212_dir = ROOT / "212trading"
    spec = importlib.util.spec_from_file_location("t212_wf_replay", str(t212_dir / "replay.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _build_venue_evaluator(venue: str, source_report: dict, baseline_dir: Path | None = None):
    """Return (base_params, base_fee, evaluate_segment_fn)."""
    norm_venue = venue.lower()
    raw_params = source_report.get("strategy_params", {})

    if norm_venue in ("kraken", "binance"):
        base_params = StratParams.from_dict(raw_params)
        base_fee = float(source_report.get("fee_pct_per_leg") or (0.26 if norm_venue == "kraken" else 0.10))
        return base_params, base_fee, _segment_result

    if norm_venue == "hyperliquid":
        hl_replay = _load_hl_replay()
        runtime_cfg = source_report.get("runtime", {})
        engine = str(runtime_cfg.get("engine") or raw_params.get("engine") or "perp").lower()
        base_fee = float(source_report.get("fee_pct_per_leg") or raw_params.get("fee_pct") or 0.035)

        if engine == "spot":
            defaults = {
                "currency": "USDC",
                "entry_amount": 50.0,
                "entry_discount_pct": 0.2,
                "dca_amount": 30.0,
                "dca_drop_pct": 2.0,
                "check_minutes": 60.0,
                "takeprofit_pct": 5.0,
                "max_budget": 500.0,
                "max_dca_buys": 10,
                "enable_takeprofit": True,
                "order_ttl_min": 120.0,
            }
            base_params = StratParams.from_dict(raw_params, defaults=defaults)

            def segment_fn(records, params, fee_pct, interval, warmup_records=(), execution=None):
                adapter = hl_replay.make_hyperliquid_replay_adapter(
                    align_spot_interval_params(params, interval),
                    bar_minutes=float(interval),
                    execution=execution,
                    fee_pct=fee_pct,
                    engine="spot",
                )
                return _evaluate_segment(records, adapter, warmup_records=warmup_records, validate_contract=True)

            return base_params, base_fee, segment_fn
        else:
            direction = str(runtime_cfg.get("direction") or raw_params.get("direction", "long"))
            coin = str(runtime_cfg.get("coin") or "HYPE")
            base_params = hl_replay.StratParams.from_dict(raw_params, direction=direction)

            def segment_fn(records, params, fee_pct, interval, warmup_records=(), execution=None):
                adapter = hl_replay.make_hyperliquid_replay_adapter(
                    params,
                    direction=params.direction,
                    coin=coin,
                    bar_minutes=float(interval),
                    execution=execution,
                    fee_pct=fee_pct,
                    engine="perp",
                )
                return _evaluate_segment(records, adapter, warmup_records=warmup_records, validate_contract=True)

            return base_params, base_fee, segment_fn

    if norm_venue in ("trading212", "t212"):
        t212_replay = _load_t212_replay()
        t212_params_cls = t212_replay._strat.StratParams
        valid_fields = {f.name for f in dataclasses.fields(t212_params_cls)}
        filtered = {k: v for k, v in raw_params.items() if k in valid_fields}
        base_params = t212_params_cls(**filtered)
        base_fee = float(source_report.get("fee_pct_per_leg") or raw_params.get("fx_fee_pct") or 0.0)
        fx_model = source_report.get("fx_model") or {}
        fx_fixed = float(fx_model["usd_per_unit"]) if fx_model.get("usd_per_unit") is not None else 1.0
        fx_invert = bool(fx_model.get("invert", False))
        fx_records = None
        if fx_model.get("mode") == "historical_asof" and fx_model.get("frozen_file"):
            fx_path = Path(fx_model["frozen_file"])
            if not fx_path.exists() and baseline_dir is not None:
                alt = baseline_dir / "datasets" / fx_path.name
                if alt.exists():
                    fx_path = alt
            if fx_path.exists():
                fx_records = load_frozen_dataset(fx_path)
        exec_meta = source_report.get("execution_model") or {}
        ppy = exec_meta.get("calendar_periods_per_year")
        periods_yr = float(ppy) if ppy is not None else None

        def segment_fn(records, params, fee_pct, interval, warmup_records=(), execution=None):
            if hasattr(params, "fx_fee_pct") and fee_pct != base_fee:
                params = dataclasses.replace(params, fx_fee_pct=fee_pct)
            adapter = t212_replay.make_t212_replay_adapter(
                params,
                bar_minutes=float(interval),
                fx_to_usd=fx_fixed,
                fx_records=fx_records,
                fx_invert=fx_invert,
                periods_per_year=periods_yr,
                execution=execution,
            )
            return _evaluate_segment(records, adapter, warmup_records=warmup_records, validate_contract=True)

        return base_params, base_fee, segment_fn

    raise ValueError(f"Unsupported venue: {venue}")


def _segment_result(
    records: list[dict],
    params: StratParams,
    fee_pct: float,
    interval: int,
    warmup_records: list[dict] | tuple = (),
    execution: ExecutionModel | None = None,
) -> dict:
    interval_params = align_spot_interval_params(params, interval)
    adapter = lambda data, warmup=(), _context=None: run_replay(
        data,
        interval_params,
        fee_pct=fee_pct,
        bar_minutes=interval,
        warmup_ohlc=warmup,
        execution=execution,
    )
    return _evaluate_segment(
        records,
        adapter,
        warmup_records=warmup_records,
        validate_contract=True,
    )


def _candidate_windows(
    datasets: dict,
    params,
    fee_pct: float,
    execution,
    segment_fn: Any | None = None,
) -> list[dict]:
    eval_fn = segment_fn or _segment_result
    windows = []
    for interval, (records, sizes, warmup_bars) in sorted(datasets.items()):
        folds = walk_forward_splits(
            len(records), train_size=sizes["train"],
            validation_size=sizes["validation"], test_size=sizes["test"],
            step_size=sizes["step"],
        )
        for fold_index, fold in enumerate(folds, start=1):
            warmup = records[max(0, fold.test.start - warmup_bars):fold.test.start]
            segment = eval_fn(
                records[fold.test], params, fee_pct, interval, warmup_records=warmup,
                execution=execution,
            )
            metrics = segment["metrics"]
            windows.append({
                "key": f"{interval}m/fold-{fold_index}",
                "interval": interval,
                "fold": fold_index,
                "start_utc": segment["start_utc"],
                "end_utc": segment["end_utc"],
                "return_pct": metrics["return_pct"],
                "max_drawdown_pct": metrics["max_drawdown_pct"],
                "buy_hold_return_pct": segment["buy_hold_return_pct"],
                "cycles": metrics["cycles"],
                "fills": metrics["fills"],
            })
    return windows


def _markdown(report: dict, venue: str = "Kraken") -> str:
    display_venue = venue.capitalize() if venue.lower() not in ("t212", "trading212") else "Trading 212"
    return format_comparison_markdown(
        report, title=f"{display_venue} walk-forward robustness comparison"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("baseline_report", type=Path)
    parser.add_argument("--output-dir", type=Path)
    parser.add_argument(
        "--venue", choices=("kraken", "binance", "hyperliquid", "trading212", "t212"),
        default=None, help="Explicit venue override; defaults to auto-detect from report",
    )
    parser.add_argument(
        "--fee-stress", default=None,
        help="fee-uri per leg, procente (defaults to venue standard stress schedule)",
    )
    parser.add_argument(
        "--candidate-set", choices=("standard", "hype-240"), default="standard",
    )
    args = parser.parse_args(argv)

    baseline_path = args.baseline_report.expanduser().resolve()
    source_report = _load_report(baseline_path)
    venue = _detect_venue(source_report, args.venue)
    datasets = _load_datasets(source_report, baseline_dir=baseline_path.parent)
    if args.candidate_set == "hype-240" and set(datasets) != {240}:
        parser.error("candidate set hype-240 requires a baseline containing only the 240 interval")

    base_params, base_fee, segment_fn = _build_venue_evaluator(
        venue, source_report, baseline_dir=baseline_path.parent
    )
    valid_exec_fields = {f.name for f in dataclasses.fields(ExecutionModel)}
    filtered_exec = {
        k: v for k, v in source_report.get("execution_model", {}).items() if k in valid_exec_fields
    }
    execution = ExecutionModel(**filtered_exec)

    results = {}
    candidates = hype_240_candidates() if args.candidate_set == "hype-240" else default_candidates()
    valid_param_fields = {f.name for f in dataclasses.fields(base_params.__class__)}
    for candidate in candidates:
        incompatible_keys = [k for k in candidate.overrides if k not in valid_param_fields]
        if incompatible_keys:
            continue
        params = dataclasses.replace(base_params, **candidate.overrides)
        windows = _candidate_windows(datasets, params, base_fee, execution, segment_fn)
        results[candidate.name] = {
            "description": candidate.description,
            "overrides": candidate.overrides,
            "summary": summarize_test_windows(windows),
            "by_interval": {
                str(interval): summarize_test_windows([
                    window for window in windows if window["interval"] == interval
                ])
                for interval in sorted(datasets)
            },
            "windows": windows,
        }

    live_windows = results["live"]["windows"]
    for name, candidate in results.items():
        candidate["relative_to_live"] = _relative(candidate["windows"], live_windows)
        candidate["dominates_live"] = (
            name != "live"
            and _dominates(candidate["summary"], results["live"]["summary"])
        )

    fee_stress_str = args.fee_stress or DEFAULT_FEE_STRESS.get(venue, "0.16,0.26,0.35,0.50")
    fee_stress = {}
    for fee_text in fee_stress_str.split(","):
        fee = float(fee_text.strip())
        if fee < 0:
            parser.error("the fee cannot be negative")
        windows = _candidate_windows(datasets, base_params, fee, execution, segment_fn)
        fee_key = f"{fee:.3f}".rstrip("0").rstrip(".") if round(fee, 2) != round(fee, 3) else f"{fee:.2f}"
        fee_stress[fee_key] = {
            "summary": summarize_test_windows(windows),
            "windows": windows,
        }

    generated_at = dt.datetime.now(tz=dt.timezone.utc)
    report = {
        "schema_version": 1,
        "venue": venue,
        "generated_at_utc": generated_at.isoformat(),
        "source_baseline_report": str(baseline_path),
        "method": {
            "candidate_style": (
                f"pre-registered {args.candidate_set} candidate set; no automatic selection"
            ),
            "comparison_dimensions": [
                "mean_return_pct", "worst_return_pct", "worst_max_drawdown_pct",
            ],
            "window_weighting": "equal across all timeframe/fold TEST windows",
            "execution_model": dataclasses.asdict(execution),
        },
        "candidates": results,
        "pareto_frontier": _pareto_names(results),
        "dominates_live": sorted(
            name for name, item in results.items() if item["dominates_live"]
        ),
        "fee_stress": fee_stress,
    }

    output_dir = (
        args.output_dir.expanduser().resolve()
        if args.output_dir else baseline_path.parent / "comparisons"
    )
    output_dir.mkdir(parents=True, exist_ok=True)
    stamp = generated_at.strftime("%Y%m%dT%H%M%SZ")
    json_path = output_dir / f"comparison_{stamp}.json"
    markdown_path = output_dir / f"comparison_{stamp}.md"
    with json_path.open("w", encoding="utf-8") as handle:
        json.dump(report, handle, indent=2, ensure_ascii=False)
    with markdown_path.open("w", encoding="utf-8") as handle:
        handle.write(_markdown(report, venue=venue))

    print(f"Venue: {venue}")
    print(f"Comparison JSON: {json_path}")
    print(f"Comparison Markdown: {markdown_path}")
    print(f"Pareto: {', '.join(report['pareto_frontier'])}")
    print(f"Dominates live: {', '.join(report['dominates_live']) or '-'}")
    for name, item in sorted(
            results.items(), key=lambda pair: pair[1]["summary"]["mean_return_pct"],
            reverse=True)[:5]:
        summary = item["summary"]
        relative = item["relative_to_live"]
        print(
            f"{name}: mean={summary['mean_return_pct']:+.3f}% "
            f"worst={summary['worst_return_pct']:+.3f}% "
            f"worstDD={summary['worst_max_drawdown_pct']:.3f}% "
            f"W/T/L={relative['wins_vs_live']}/{relative['ties_vs_live']}/"
            f"{relative['losses_vs_live']}"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
