#!/usr/bin/env python3
"""Robust one-factor comparison runner for walk-forward baseline configurations.

Venue-agnostic: consumes the baseline report and frozen CSVs generated by any
venue baseline runner (Kraken, Binance, Hyperliquid, Trading 212). It searches
no combinations and changes no live config: ablations change a single mechanism.
"""
